import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

function fail(message) { throw new Error(message) }
function readJson(file) { return JSON.parse(fs.readFileSync(file, 'utf8')) }
function sqlLiteral(value) { return `'${String(value).replaceAll("'", "''")}'` }

export function loadControl(file) {
  const c = readJson(file)
  if (c?.version !== 1) fail('control version must be 1')
  if (c?.release !== 'pr1690-regulatory-tier-production-activation') fail('unexpected release id')
  if (c?.production_project_ref !== 'zvxdgdkukjrrwamdpqrg') fail('unexpected production project')
  const expected = [
    ['20260829120000','live_tier_pipeline_hardening','supabase/migrations/20260829120000_live_tier_pipeline_hardening.sql','8a791744e923596ddc9cd6b1d9848bcb60dc7081'],
    ['20260829130000','tier_optimization_batch2','supabase/migrations/20260829130000_tier_optimization_batch2.sql','cd9c7b9b96bcbb52a0dd551684de488afa18feda'],
    ['20260829160000','fix_europe_regulatory_tiers','supabase/migrations/20260829160000_fix_europe_regulatory_tiers.sql','6d8e29d67b3f9458e9926d1525bfc5dd3fe7c9dc'],
  ]
  if (!Array.isArray(c.migrations) || c.migrations.length !== expected.length) fail('exactly three migrations are required')
  for (let i=0;i<expected.length;i++) {
    const m=c.migrations[i], e=expected[i]
    if (m?.version!==e[0] || m?.name!==e[1] || m?.file!==e[2] || m?.git_blob_sha!==e[3]) fail(`unexpected migration binding at index ${i}`)
  }
  if (c?.activation?.required_dispatch_action !== 'APPLY_PR1690_REGULATORY_TIERS') fail('unexpected dispatch action')
  if (c?.activation?.required_environment !== 'production-database') fail('unexpected protected environment')
  return c
}

export function gitBlobSha(file) {
  return execFileSync('git',['hash-object',file],{encoding:'utf8'}).trim()
}

export function verifyBoundMigrations(control) {
  return control.migrations.map((m) => {
    if (!fs.existsSync(m.file)) fail(`migration file missing: ${m.file}`)
    const actual = gitBlobSha(m.file)
    if (actual !== m.git_blob_sha) fail(`migration blob mismatch for ${m.version}: expected ${m.git_blob_sha}, got ${actual}`)
    return actual
  })
}

function assertNoTransactionBoundary(sql, version) {
  const stripped = sql.replace(/--.*$/gm,'')
  if (/^\s*(begin|commit|rollback)\s*;/gim.test(stripped)) fail(`migration ${version} contains an outer transaction boundary`)
}

export function buildActivationSql(control) {
  const chunks = ['-- Generated by scripts/pr1690-regulatory-tier-activation-control.mjs.']
  for (const m of control.migrations) {
    const sql = fs.readFileSync(m.file,'utf8').trim()
    if (!sql) fail(`migration body empty: ${m.version}`)
    assertNoTransactionBoundary(sql,m.version)
    const idempotency = `gitblob:${m.git_blob_sha}`
    chunks.push(
      '',
      `-- Exact bound migration ${m.version}: ${m.file}`,
      `-- Git blob: ${m.git_blob_sha}`,
      'BEGIN;',
      sql,
      '',
      'INSERT INTO supabase_migrations.schema_migrations',
      '  (version, name, created_by, idempotency_key)',
      'VALUES',
      `  (${sqlLiteral(m.version)}, ${sqlLiteral(m.name)}, ${sqlLiteral(control.activation.ledger_created_by)}, ${sqlLiteral(idempotency)});`,
      'COMMIT;'
    )
  }
  chunks.push('')
  return chunks.join('\n')
}

function parseArgs(argv) {
  const [command,...rest]=argv
  const args={command}
  for (let i=0;i<rest.length;i+=2) {
    const key=rest[i], value=rest[i+1]
    if (!key?.startsWith('--') || value==null) fail(`invalid CLI arguments near ${key ?? '<end>'}`)
    args[key.slice(2)]=value
  }
  return args
}

async function main() {
  const args=parseArgs(process.argv.slice(2))
  if (!args.command) return
  const controlPath=args.control ?? 'supabase/release-controls/pr1690-regulatory-tier-activation.json'
  const control=loadControl(controlPath)
  if (args.command==='verify') {
    const blobs=verifyBoundMigrations(control)
    process.stdout.write(JSON.stringify({ok:true,blobs})+'\n')
    return
  }
  if (args.command==='generate') {
    verifyBoundMigrations(control)
    if (!args.out) fail('--out is required')
    fs.mkdirSync(path.dirname(args.out),{recursive:true})
    fs.writeFileSync(args.out,buildActivationSql(control))
    return
  }
  fail(`unknown command: ${args.command}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  main().catch((error)=>{ console.error(error.message); process.exit(1) })
}
