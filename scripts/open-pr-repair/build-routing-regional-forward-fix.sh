# Regional routing definitions

Status: active internal routing control. This document controls how a retained
regional or bloc label is matched to operator country codes.

## Data sources

- ISO-2/ISO-3 conversion is generated with `pycountry 24.6.1`.
- Region and subregion values come from Harbourview's checked-in 248-row country
  identity table, derived from the UN M49 classification.
- European Union membership is the current 27-member list published by the
  European Union as verified on 2026-08-02.

## Audience rules

- `Africa`, `Americas`, `Asia`, `Europe`, and `Oceania` match the corresponding
  UN M49 macro-region.
- `LATAM`, `Latin America`, and `Latin America and the Caribbean` match UN M49
  Caribbean, Central America, and South America subregions. They do not include
  Northern America.
- `Caribbean` matches only the UN M49 Caribbean subregion.
- `European Union` / `EU` matches the controlled 27-member ISO-2 set. Cyprus is
  included despite its UN M49 placement in Western Asia; the United Kingdom is
  excluded.
- `Middle East` uses the explicit Harbourview operational definition of UN M49
  Western Asia plus Egypt. It does not widen to all Asia or all MENA.
- `Pacific` matches the UN M49 Oceania macro-region.
- An invalid or unmapped operator country does not fail open into every regional
  audience.

Any membership or definition change requires updating this document, the
controlled generated data/tests, and the evidence log in the same PR.
EOF

