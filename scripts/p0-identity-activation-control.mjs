import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

function fail(message) {
  throw new Error(message)
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`
}

export function loadControl(file) {
  const control = readJson(file)
  const migration = control?.migration
  if (control?.version !== 1) fail('control version must be 1')
  if (control?.release !== 'p0-identity-org-context-production-activation') fail('unexpected release id')
  if (control?.production_project_ref !== 'zvxdgdkukjrrwamdpqrg') fail('unexpected production project')
  if (migration?.version !== '20260814122000') fail('unexpected migration version')
  if (migration?.name !== 'p0_identity_org_context') fail('unexpected migration name')
  if (migration?.file !== 'supabase/migrations/20260814122000_p0_identity_org_context.sql') fail('unexpected migration file')
  if (!/^[0-9a-f]{40}$/.test(migration?.git_blob_sha ?? '')) fail('migration git_blob_sha must be a 40-character SHA-1')
  if (!Array.isArray(control.expected_later_applied_versions) || control.expected_later_applied_versions.length === 0) fail('expected later-applied migration set is required')
  if (!control.expected_preflight_snapshot || typeof control.expected_preflight_snapshot !== 'object') fail('expected preflight snapshot is required')
  if (control?.activation?.required_dispatch_action !== 'APPLY_P0_IDENTITY_ORG_CONTEXT') fail('unexpected dispatch action')
  if (control?.activation?.required_environment !== 'production-database') fail('unexpected protected environment')
  return control
}

export function gitBlobSha(file) {
  return execFileSync('git', ['hash-object', file], { encoding: 'utf8' }).trim()
}

export function verifyBoundMigration(control, migrationPath = control.migration.file) {
  const expectedPath = path.normalize(control.migration.file)
  const actualPath = path.normalize(migrationPath)
  if (actualPath !== expectedPath) fail(`refusing non-bound migration path: ${migrationPath}`)
  if (!fs.existsSync(migrationPath)) fail(`migration file missing: ${migrationPath}`)
  const actualBlob = gitBlobSha(migrationPath)
  if (actualBlob !== control.migration.git_blob_sha) {
    fail(`migration blob mismatch: expected ${control.migration.git_blob_sha}, got ${actualBlob}`)
  }
  return actualBlob
}

export function stripOuterTransaction(sql) {
  const normalized = sql.replace(/^\uFEFF/, '').trim()
  if (!/^begin\s*;/i.test(normalized)) fail('migration must begin with BEGIN;')
  if (!/commit\s*;$/i.test(normalized)) fail('migration must end with COMMIT;')
  const withoutBegin = normalized.replace(/^begin\s*;\s*/i, '')
  const inner = withoutBegin.replace(/\s*commit\s*;$/i, '').trim()
  if (!inner) fail('migration body is empty')
  return inner
}

export function buildActivationSql(control, migrationSql) {
  const inner = stripOuterTransaction(migrationSql)
  const { version, name, git_blob_sha: blob } = control.migration
  const createdBy = control.activation.ledger_created_by
  const idempotencyKey = control.activation.idempotency_key
  if (idempotencyKey !== `gitblob:${blob}`) fail('idempotency key must bind the exact Git blob')

  return [
    '-- Generated by scripts/p0-identity-activation-control.mjs.',
    `-- Exact bound migration: ${control.migration.file}`,
    `-- Git blob: ${blob}`,
    'BEGIN;',
    '',
    inner,
    '',
    'INSERT INTO supabase_migrations.schema_migrations',
    '  (version, name, created_by, idempotency_key)',
    'VALUES',
    `  (${sqlLiteral(version)}, ${sqlLiteral(name)}, ${sqlLiteral(createdBy)}, ${sqlLiteral(idempotencyKey)});`,
    '',
    'COMMIT;',
    '',
  ].join('\n')
}

export function assertExactJson(actualFile, expected) {
  const actual = readJson(actualFile)
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    fail(`snapshot mismatch\nexpected=${JSON.stringify(expected)}\nactual=${JSON.stringify(actual)}`)
  }
}

function parseArgs(argv) {
  const [command, ...rest] = argv
  const args = { command }
  for (let i = 0; i < rest.length; i += 2) {
    const key = rest[i]
    const value = rest[i + 1]
    if (!key?.startsWith('--') || value == null) fail(`invalid CLI arguments near ${key ?? '<end>'}`)
    args[key.slice(2)] = value
  }
  return args
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  if (!args.command) return
  const controlPath = args.control ?? 'supabase/release-controls/p0-identity-org-context-activation.json'
  const control = loadControl(controlPath)

  if (args.command === 'verify') {
    verifyBoundMigration(control, args.migration ?? control.migration.file)
    process.stdout.write(JSON.stringify({ ok: true, migration: control.migration }) + '\n')
    return
  }

  if (args.command === 'generate') {
    const migrationPath = args.migration ?? control.migration.file
    verifyBoundMigration(control, migrationPath)
    const output = args.out
    if (!output) fail('--out is required')
    fs.mkdirSync(path.dirname(output), { recursive: true })
    fs.writeFileSync(output, buildActivationSql(control, fs.readFileSync(migrationPath, 'utf8')))
    return
  }

  if (args.command === 'assert-preflight-snapshot') {
    if (!args.file) fail('--file is required')
    assertExactJson(args.file, control.expected_preflight_snapshot)
    return
  }

  if (args.command === 'assert-later-set') {
    if (!args.file) fail('--file is required')
    assertExactJson(args.file, control.expected_later_applied_versions)
    return
  }

  fail(`unknown command: ${args.command}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  main().catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
