export const MARKETPLACE_CATEGORY_KEYS = MARKETPLACE_TAXONOMY.map((category) => category.key)

export function getMarketplaceCategory(key: string | null | undefined) {
  if (!key) return undefined
  return MARKETPLACE_TAXONOMY.find((category) => category.key === key)
}

export function isMarketplaceCategoryKey(value: string): value is MarketplaceCategoryKey {
  return MARKETPLACE_CATEGORY_KEYS.includes(value as MarketplaceCategoryKey)
}

export function getPublicMarketplaceCategories() {
  return MARKETPLACE_TAXONOMY.filter((category) => category.publicVisibilityMode !== 'admin_only')
}
