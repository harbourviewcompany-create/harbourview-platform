import type {
  MarketplaceCategoryKey,
  MarketplaceListingTypeKey,
  MarketplaceMonetizationPath,
  MarketplaceRecordType,
  MarketplaceSection,
  MarketplaceVisibilityMode,
} from './marketplaceTypes'

export type MarketplaceCategoryDefinition = {
  key: MarketplaceCategoryKey
  publicLabel: string
  internalLabel: string
  route: string
  parentKey?: MarketplaceCategoryKey
  marketplaceSection: MarketplaceSection
  allowedListingTypes: MarketplaceListingTypeKey[]
  allowedRecordTypes: MarketplaceRecordType[]
  publicVisibilityMode: MarketplaceVisibilityMode
  defaultCtaLabel: string
  defaultMonetizationPath: MarketplaceMonetizationPath
  requiresLicenseReview: boolean
  restrictedByDefault: boolean
  requiredVerificationFields: string[]
  requiredPublicFields: string[]
  allowedPublicFields: string[]
  forbiddenPublicClaims: string[]
}

const DEFAULT_PUBLIC_FIELDS = [
  'id',
  'slug',
  'title',
  'description',
  'category',
  'subcategory',
  'marketplace_section',
  'product_type',
  'region',
  'condition',
  'location_country',
  'location_region',
  'price_display',
  'price_currency',
  'is_featured',
  'high_level_specs',
  'created_at',
  'cta_label',
]

const DEFAULT_FORBIDDEN_CLAIMS = [
  'guaranteed availability',
  'verified seller contact',
  'certified supply',
  'guaranteed licence status',
  'guaranteed transaction',
]

function category(input: Omit<MarketplaceCategoryDefinition, 'requiredPublicFields' | 'allowedPublicFields' | 'forbiddenPublicClaims'> & Partial<Pick<MarketplaceCategoryDefinition, 'requiredPublicFields' | 'allowedPublicFields' | 'forbiddenPublicClaims'>>): MarketplaceCategoryDefinition {
  return {
    ...input,
    requiredPublicFields: input.requiredPublicFields ?? ['id', 'title', 'description', 'category', 'marketplace_section', 'created_at'],
    allowedPublicFields: input.allowedPublicFields ?? DEFAULT_PUBLIC_FIELDS,
    forbiddenPublicClaims: input.forbiddenPublicClaims ?? DEFAULT_FORBIDDEN_CLAIMS,
  }
}

